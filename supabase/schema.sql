-- 1) Create the complaint table
create table if not exists public.citizen_complaints (
  id bigint generated by default as identity primary key,
  citizen_name text not null,
  subject text not null,
  description text not null,
  token text not null unique,
  uploaded_file_name text,
  uploaded_file_url text,
  status text not null default 'new' check (status in ('new', 'in_progress', 'resolved')),
  created_at timestamptz not null default now()
);

-- 2) Open table access for app usage
alter table public.citizen_complaints enable row level security;

create policy "Allow public read access to citizen complaints"
  on public.citizen_complaints
  for select
  using (true);

create policy "Allow public insert access to citizen complaints"
  on public.citizen_complaints
  for insert
  with check (true);

-- 3) Create storage bucket for complaint images
insert into storage.buckets (id, name, public)
values ('citizen-complaints', 'citizen-complaints', true)
on conflict (id) do nothing;

-- 4) Storage policies
create policy "Allow public upload of complaint images"
  on storage.objects
  for insert
  with check (bucket_id = 'citizen-complaints');

create policy "Allow public view of complaint images"
  on storage.objects
  for select
  using (bucket_id = 'citizen-complaints');
